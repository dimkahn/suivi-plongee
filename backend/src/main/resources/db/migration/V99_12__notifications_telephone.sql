-- ============================================================
--  Notifications sur le téléphone (Web Push, demande du club, 2026).
--  cle_vapid : la paire de clés du serveur (RFC 8292), tirée au premier
--  besoin et gardée ici, une ligne : rien à régler au déploiement.
--  sejour_abonnement_push : le téléphone d'un participant qui a activé
--  les notifications du séjour (adresse du service de notification et
--  clés de chiffrement données par le navigateur). Retirer le participant,
--  ou désactiver, l'efface ; un abonnement dit expiré aussi.
-- ============================================================

CREATE TABLE cle_vapid (
    id              INTEGER      NOT NULL PRIMARY KEY,
    cle_publique    VARCHAR(100) NOT NULL,
    cle_privee      VARCHAR(100) NOT NULL,
    cree_le         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cle_vapid_unique CHECK (id = 1)
);

CREATE TABLE sejour_abonnement_push (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id  BIGINT        NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    endpoint        VARCHAR(1000) NOT NULL,
    p256dh          VARCHAR(200)  NOT NULL,
    auth            VARCHAR(100)  NOT NULL,
    -- Vrai : activé dans l'appli (compte) ; la notification ouvre /sejours/{id}, sinon /sejour/{code}.
    depuis_appli    BOOLEAN       NOT NULL DEFAULT FALSE,
    cree_le         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sejour_abonnement_push UNIQUE (participant_id, endpoint)
);
CREATE INDEX ix_sejour_abonnement_push ON sejour_abonnement_push(participant_id);
