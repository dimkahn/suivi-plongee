-- ============================================================
--  Validation d'une compétence (choix du club, 2026).
--
--  1. Exercices de maîtrise obligatoires : une compétence ne se valide
--     qu'une fois acquis tous ses exercices de maîtrise marqués
--     obligatoires (exercice_competence.obligatoire, coché dans
--     /admin/exercices). Le MFT exige que chaque critère de la
--     compétence soit validé : on marque d'office, pour chaque critère
--     qui a un exercice de maîtrise actif, celui qui couvre le plus de
--     critères (puis le premier dans l'ordre). Les critères sans
--     exercice de maîtrise (N1 « Départ plage », « Ventilation sur
--     tuba », blocs de théorie) n'en ont pas. Le club ajuste ensuite.
--
--  2. Accord des encadrants du groupe : la validation est proposée aux
--     encadrants attitrés du groupe d'entraînement de l'élève, comme un
--     vote ; elle est faite dès que la moitié d'entre eux ont donné leur
--     accord. Un référent du groupe valide seul. Une ligne par accord,
--     en ajout seul ; la validation elle-même reste dans
--     validation_competence.
-- ============================================================

ALTER TABLE exercice_competence ADD COLUMN obligatoire BOOLEAN DEFAULT FALSE NOT NULL;

UPDATE exercice_competence SET obligatoire = TRUE
 WHERE id IN (
       SELECT (SELECT e.id
                 FROM exercice_competence e
                 JOIN exercice_competence_critere ec ON ec.exercice_id = e.id
                WHERE ec.critere_id = c.id AND e.phase = 'MAITRISE' AND e.actif = TRUE
                ORDER BY (SELECT COUNT(*) FROM exercice_competence_critere n WHERE n.exercice_id = e.id) DESC,
                         e.ordre, e.id
                FETCH FIRST 1 ROWS ONLY)
         FROM critere c);

CREATE TABLE accord_validation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cursus_id    BIGINT NOT NULL REFERENCES cursus(id) ON DELETE CASCADE,
    bloc_id      BIGINT NOT NULL REFERENCES bloc_competence(id),
    moniteur_id  BIGINT NOT NULL REFERENCES utilisateur(id),
    date_accord  DATE NOT NULL,
    CONSTRAINT uq_accord_validation UNIQUE (cursus_id, bloc_id, moniteur_id)
);

CREATE INDEX ix_accord_validation_cursus ON accord_validation(cursus_id);
