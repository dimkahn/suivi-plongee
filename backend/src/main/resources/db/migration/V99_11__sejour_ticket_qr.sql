-- ============================================================
--  Connexion d'un participant par QR code (demande du club, 2026).
--  L'organisateur montre sur son téléphone un QR code fabriqué pour
--  un participant ; celui-ci le scanne et entre dans le séjour sans
--  e-mail ni code. Le ticket du QR code : son empreinte seulement,
--  une minute, un seul usage ; il ouvre un jeton (sejour_jeton_acces)
--  valable jusqu'à un mois après la fin du séjour. Retirer le
--  participant les efface.
-- ============================================================

CREATE TABLE sejour_ticket_qr (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id  BIGINT       NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    empreinte       VARCHAR(64)  NOT NULL,
    expire_le       TIMESTAMP    NOT NULL,
    cree_le         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sejour_ticket_qr UNIQUE (empreinte)
);
CREATE INDEX ix_sejour_ticket_qr ON sejour_ticket_qr(participant_id);
