-- ============================================================
--  Règles apprises des corrections faites après la lecture d'une note
--  de frais de séjour (demande du club, 2026).
--
--  La note est lue sur le téléphone (OCR) ; quand celui qui saisit garde
--  ou corrige la catégorie, ou corrige le total, l'écran envoie une leçon :
--  le commerçant (première ligne lisible du ticket), et la catégorie
--  choisie ou le libellé de la ligne qui portait le bon total. Une ligne
--  par (commerçant, sorte, valeur), avec le nombre de fois où elle a été
--  apprise : la plus souvent apprise l'emporte. Ni photo, ni texte du
--  ticket, ni montant, ni auteur : rien de personnel. Commune à tout le
--  club (pas de lien au séjour) : chacun profite des corrections des autres.
-- ============================================================

CREATE TABLE regle_lecture_note (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enseigne  VARCHAR(60) NOT NULL,
    -- CATEGORIE (valeur : CategorieDepense) ou LIBELLE_TOTAL (valeur : « A REGLER »…)
    sorte     VARCHAR(20) NOT NULL,
    valeur    VARCHAR(60) NOT NULL,
    nombre    INT         NOT NULL DEFAULT 1,
    maj_le    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_regle_lecture_note UNIQUE (enseigne, sorte, valeur)
);
