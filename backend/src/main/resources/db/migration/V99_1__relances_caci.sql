-- Relances automatiques des CACI qui arrivent à échéance (spec
-- docs/specs/2026-10-21-relances-caci). Numéro 99.1 : la suite « sous 100 »
-- s'arrête à V99, V100 et au-delà sont à la démo (db/demo) ; voir le skill
-- nouvelle-migration. Tables en SQL seul (RelancesCaciService), sans entité
-- JPA ni Envers : ajout seul, hors purge.

-- Trace des e-mails de relance CACI partis (R19), lue par les administrateurs.
-- Supprimée 2 ans après l'envoi (R20). Noms recopiés (pas de clé étrangère) :
-- la trace dit à qui on a écrit ce jour-là. Ni fin de validité, ni mention
-- élève ou moniteur, ni sujet ni corps de l'e-mail.
CREATE TABLE relance_caci_envoi (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envoye_le            DATE         NOT NULL,          -- D, date du club (R22)
    destinataire_nom     VARCHAR(80)  NOT NULL,
    destinataire_prenom  VARCHAR(80)  NOT NULL,
    destinataire_email   VARCHAR(180) NOT NULL
);
CREATE INDEX idx_relance_caci_envoi_date ON relance_caci_envoi (envoye_le);

-- Personnes concernées par un envoi, par leur nom et prénom seulement (R19).
CREATE TABLE relance_caci_envoi_personne (
    envoi_id  BIGINT      NOT NULL REFERENCES relance_caci_envoi(id) ON DELETE CASCADE,
    ordre     INT         NOT NULL,
    nom       VARCHAR(80) NOT NULL,
    prenom    VARCHAR(80) NOT NULL,
    PRIMARY KEY (envoi_id, ordre)
);

-- Relances déjà faites, pour n'en faire qu'une par personne, par fin de
-- validité et par moment (R8), et citer « Sans CACI renseigné » au plus une
-- fois par semaine (R12). Jamais exposée par l'API : elle garde la fin de
-- validité, que la trace n'a pas le droit de porter.
CREATE TABLE relance_caci_faite (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  BIGINT      REFERENCES utilisateur(id) ON DELETE CASCADE,
    eleve_id        BIGINT      REFERENCES eleve(id) ON DELETE CASCADE,
    moment          VARCHAR(10) NOT NULL CHECK (moment IN ('BIENTOT', 'JOUR_J', 'SANS_CACI')),
    fin_validite    DATE,
    faite_le        DATE        NOT NULL,
    CHECK ((utilisateur_id IS NULL AND eleve_id IS NOT NULL) OR (utilisateur_id IS NOT NULL AND eleve_id IS NULL)),
    CHECK ((moment = 'SANS_CACI' AND fin_validite IS NULL) OR (moment <> 'SANS_CACI' AND fin_validite IS NOT NULL)),
    -- La double relance est impossible en base (R8, R22) ; NULL distincts : SANS_CACI non concerné.
    CONSTRAINT uk_relance_caci_moniteur UNIQUE (utilisateur_id, fin_validite, moment),
    CONSTRAINT uk_relance_caci_eleve    UNIQUE (eleve_id, fin_validite, moment)
);
