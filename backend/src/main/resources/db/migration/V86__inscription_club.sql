-- ============================================================
--  Inscription au club à jour, saison par saison (demande du club, 2026).
--
--  Une ligne = l'ADMIN a noté que l'élève est à jour de son inscription
--  au club pour cette saison (pastille « Inscription OK » verte sur sa
--  carte de l'administration des élèves) ; pas de ligne = KO, en rouge.
--  À la saison suivante, tout le monde repart KO jusqu'à ce qu'on le note :
--  rien à décocher à la rentrée, et l'historique reste.
--
--  Distinct de `adhesion_saison` (V9) et de `cursus`, qui disent qu'un
--  élève fait partie de la saison, pas qu'il a réglé son inscription.
--  Pas d'audit Envers : qui l'a notée et quand suffisent (saisi_par_id,
--  inscrit_le).
-- ============================================================

CREATE TABLE inscription_club (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleve_id      BIGINT    NOT NULL REFERENCES eleve(id) ON DELETE CASCADE,
    saison_id     BIGINT    NOT NULL REFERENCES saison(id) ON DELETE CASCADE,
    inscrit_le    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    saisi_par_id  BIGINT    REFERENCES utilisateur(id) ON DELETE SET NULL,
    CONSTRAINT uq_inscription_club UNIQUE (eleve_id, saison_id)
);
CREATE INDEX idx_inscription_club_saison ON inscription_club(saison_id);
