-- ============================================================
--  Partage des frais d'un séjour (V75) : les dépenses avancées par
--  un participant (gîte, location de voiture, courses, plongées...),
--  réparties entre les participants concernés selon leurs parts,
--  et les remboursements faits entre eux. Les soldes et les
--  remboursements à faire sont calculés par le serveur
--  (FraisSejour), jamais stockés.
--
--  Montants en centimes (entiers) : pas d'arrondi flottant.
--  Un participant qui a payé, qui a une part ou un remboursement
--  ne se retire plus du séjour (règle du service) : les comptes
--  resteraient faux.
-- ============================================================

-- categorie : HEBERGEMENT, TRANSPORT, REPAS, PLONGEE ou AUTRE.
CREATE TABLE sejour_depense (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id         BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    libelle           VARCHAR(160) NOT NULL,
    categorie         VARCHAR(20) NOT NULL,
    montant_centimes  BIGINT NOT NULL,
    payeur_id         BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    jour              DATE,
    CONSTRAINT ck_sejour_depense_montant CHECK (montant_centimes > 0)
);
CREATE INDEX ix_sejour_depense_sortie ON sejour_depense(sortie_id);

-- parts : poids dans la répartition (1 par défaut, 2 pour un couple...).
CREATE TABLE sejour_depense_part (
    depense_id      BIGINT NOT NULL REFERENCES sejour_depense(id) ON DELETE CASCADE,
    participant_id  BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    parts           INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (depense_id, participant_id),
    CONSTRAINT ck_sejour_depense_parts CHECK (parts BETWEEN 1 AND 20)
);

-- Un remboursement fait : de_id a versé montant à a_id.
CREATE TABLE sejour_versement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id         BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    de_id             BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    a_id              BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    montant_centimes  BIGINT NOT NULL,
    jour              DATE,
    CONSTRAINT ck_sejour_versement_montant CHECK (montant_centimes > 0),
    CONSTRAINT ck_sejour_versement_personnes CHECK (de_id <> a_id)
);
CREATE INDEX ix_sejour_versement_sortie ON sejour_versement(sortie_id);
