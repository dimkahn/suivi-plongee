-- ============================================================
--  Validation d'un critère technique seul (choix du club, 2026),
--  comme celle d'une compétence entière (V93) : proposée aux
--  encadrants du groupe d'entraînement de l'élève, faite dès que la
--  moitié d'entre eux ont donné leur accord, tout de suite par un
--  référent du groupe. Exige le critère acquis et ses exercices de
--  maîtrise obligatoires acquis.
--
--  - validation_critere : le critère validé, une fois par cursus ;
--  - accord_validation_critere : un accord par encadrant.
--  Ajout seul, comme les notes.
-- ============================================================

CREATE TABLE validation_critere (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cursus_id        BIGINT NOT NULL REFERENCES cursus(id) ON DELETE CASCADE,
    critere_id       BIGINT NOT NULL REFERENCES critere(id),
    moniteur_id      BIGINT NOT NULL REFERENCES utilisateur(id),
    date_validation  DATE NOT NULL,
    CONSTRAINT uq_validation_critere UNIQUE (cursus_id, critere_id)
);

CREATE TABLE accord_validation_critere (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cursus_id    BIGINT NOT NULL REFERENCES cursus(id) ON DELETE CASCADE,
    critere_id   BIGINT NOT NULL REFERENCES critere(id),
    moniteur_id  BIGINT NOT NULL REFERENCES utilisateur(id),
    date_accord  DATE NOT NULL,
    CONSTRAINT uq_accord_validation_critere UNIQUE (cursus_id, critere_id, moniteur_id)
);

CREATE INDEX ix_validation_critere_cursus ON validation_critere(cursus_id);
CREATE INDEX ix_accord_validation_critere_cursus ON accord_validation_critere(cursus_id);
