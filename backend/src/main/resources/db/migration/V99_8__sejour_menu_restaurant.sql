-- ============================================================
--  Le menu d'un restaurant du séjour (demande du club, 2026) :
--  l'organisateur importe un classeur Excel du menu (fabriqué
--  par une IA à partir d'une photo du menu, avec le prompt
--  donné par l'appli), chaque participant y choisit ses plats,
--  l'organisateur lit la commande complète.
--
--  Un menu par repas (jour, PETIT_DEJEUNER/DEJEUNER/DINER) ;
--  le réimporter remplace ses plats, donc efface les choix.
--  Prix en centimes, facultatif. Aucun commentaire libre sur
--  les choix (pas d'état de santé : voir donnees-personnelles).
--  Tout disparaît avec la sortie, un choix avec son participant.
-- ============================================================

CREATE TABLE sejour_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id   BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    jour        DATE NOT NULL,
    repas       VARCHAR(20) NOT NULL,
    restaurant  VARCHAR(200),
    UNIQUE (sortie_id, jour, repas)
);

CREATE TABLE sejour_menu_plat (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id        BIGINT NOT NULL REFERENCES sejour_menu(id) ON DELETE CASCADE,
    rang           INT NOT NULL,
    categorie      VARCHAR(100),
    nom            VARCHAR(300) NOT NULL,
    description    VARCHAR(1000),
    prix_centimes  INT
);

CREATE TABLE sejour_menu_choix (
    plat_id         BIGINT NOT NULL REFERENCES sejour_menu_plat(id) ON DELETE CASCADE,
    participant_id  BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    PRIMARY KEY (plat_id, participant_id)
);

CREATE INDEX idx_sejour_menu_choix_participant ON sejour_menu_choix (participant_id);
