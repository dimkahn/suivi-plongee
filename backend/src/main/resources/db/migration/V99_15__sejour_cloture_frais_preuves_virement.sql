-- ============================================================
--  Fin des comptes d'un séjour (demande du club, 2026).
--
--  1. Les organisateurs closent les frais : frais_clos_le posé, plus
--     aucune dépense n'est ajoutée, modifiée ni supprimée (règle du
--     service, 422), organisateurs compris ; les remboursements restent
--     possibles. Null : frais ouverts. Rouvrir remet null.
--
--  2. La preuve d'un virement (PDF, JPEG ou PNG, 5 Mo) : envoyée par
--     celui qui rembourse (de_id) à un participant ou au club (a_id
--     null), confirmée par le bénéficiaire ou un organisateur. La
--     confirmation crée le remboursement (sejour_versement) et y relie
--     la preuve (versement_id) ; tant qu'elle n'est pas confirmée, elle
--     ne compte pas dans les soldes. Gardée avec le séjour (choix du
--     club) ; lue seulement par celui qui l'envoie, le bénéficiaire et
--     les organisateurs. Annuler le remboursement la remet à confirmer.
-- ============================================================

ALTER TABLE sejour ADD COLUMN frais_clos_le TIMESTAMP;

CREATE TABLE sejour_preuve_virement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id         BIGINT       NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    de_id             BIGINT       NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    a_id              BIGINT       REFERENCES sejour_participant(id) ON DELETE CASCADE,
    montant_centimes  BIGINT       NOT NULL,
    jour              DATE,
    contenu           BYTEA        NOT NULL,
    type_contenu      VARCHAR(30)  NOT NULL CHECK (type_contenu IN ('application/pdf', 'image/jpeg', 'image/png')),
    envoyee_le        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    versement_id      BIGINT       REFERENCES sejour_versement(id) ON DELETE SET NULL,
    CONSTRAINT ck_sejour_preuve_montant CHECK (montant_centimes > 0),
    CONSTRAINT ck_sejour_preuve_personnes CHECK (a_id IS NULL OR de_id <> a_id)
);
CREATE INDEX ix_sejour_preuve_virement_sortie ON sejour_preuve_virement(sortie_id);
