-- ============================================================
--  Frais d'un séjour (V76), suite : les participants saisissent eux
--  aussi leurs dépenses, avec la photo de la note, et ceux qui n'ont
--  pas de compte y accèdent par un lien et un code reçu par e-mail.
--
--  Qui a saisi quoi : saisie_par_utilisateur_id (compte connecté) ou
--  saisie_par_participant_id (participant entré par le lien) ; seul
--  l'auteur, ou l'organisateur, modifie ou supprime ensuite.
--
--  Photos des notes : table à part (comme photo_pret), pour ne jamais
--  alourdir la lecture des frais ; JPEG ou PNG vérifiés par leur
--  signature (FraisParticipantService).
--
--  Accès sans compte : sejour.code_frais est la partie secrète de
--  l'adresse des frais du séjour (/frais/{code}) ; on y donne son
--  e-mail, on reçoit un code à 6 chiffres (sejour_code_acces : son
--  empreinte seulement, 10 minutes, 5 essais), qui ouvre un jeton
--  (sejour_jeton_acces : son empreinte seulement) valable jusqu'à
--  60 jours après la fin du séjour. Retirer le participant les efface.
-- ============================================================

ALTER TABLE sejour ADD COLUMN code_frais VARCHAR(64);
CREATE UNIQUE INDEX uq_sejour_code_frais ON sejour(code_frais);

ALTER TABLE sejour_depense ADD COLUMN saisie_par_utilisateur_id BIGINT REFERENCES utilisateur(id) ON DELETE SET NULL;
ALTER TABLE sejour_depense ADD COLUMN saisie_par_participant_id BIGINT REFERENCES sejour_participant(id) ON DELETE SET NULL;
ALTER TABLE sejour_versement ADD COLUMN saisie_par_utilisateur_id BIGINT REFERENCES utilisateur(id) ON DELETE SET NULL;
ALTER TABLE sejour_versement ADD COLUMN saisie_par_participant_id BIGINT REFERENCES sejour_participant(id) ON DELETE SET NULL;

CREATE TABLE sejour_depense_photo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depense_id    BIGINT       NOT NULL REFERENCES sejour_depense(id) ON DELETE CASCADE,
    contenu       BYTEA        NOT NULL,
    type_contenu  VARCHAR(30)  NOT NULL CHECK (type_contenu IN ('image/jpeg', 'image/png')),
    ajoutee_le    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_sejour_depense_photo ON sejour_depense_photo(depense_id);

CREATE TABLE sejour_code_acces (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id  BIGINT       NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    empreinte       VARCHAR(64)  NOT NULL,
    expire_le       TIMESTAMP    NOT NULL,
    essais          INTEGER      NOT NULL DEFAULT 0,
    cree_le         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_sejour_code_acces ON sejour_code_acces(participant_id);

CREATE TABLE sejour_jeton_acces (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id  BIGINT       NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    empreinte       VARCHAR(64)  NOT NULL,
    expire_le       TIMESTAMP    NOT NULL,
    cree_le         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sejour_jeton_acces UNIQUE (empreinte)
);
