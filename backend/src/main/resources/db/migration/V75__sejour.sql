-- ============================================================
--  Le séjour d'une sortie : participants (arrivées et départs,
--  régime alimentaire, personne à prévenir), voitures et leurs
--  passagers, logements, chambres et occupants, liste des affaires
--  à prévoir, programme jour par jour et infos pratiques.
--
--  Tout est rattaché à la sortie (V31) et disparaît avec elle.
--  Un participant est un instantané éditable, comme un membre de
--  groupe de plongeurs (V13) : le dossier élève ou le compte ne
--  sert qu'à pré-remplir, et à ouvrir le carnet du séjour au
--  participant qui a un compte.
--
--  Aucune donnée de santé : ni traitement, ni allergie, ni
--  pathologie (règle du club, voir CLAUDE.md). Le régime
--  alimentaire est une liste de cases (regimes, codes séparés par
--  des virgules) et une précision pour la cuisine ; la personne à
--  prévenir n'est qu'un nom et un téléphone, comme sur le dossier
--  élève (V18).
-- ============================================================

CREATE TABLE sejour (
    sortie_id        BIGINT PRIMARY KEY REFERENCES sortie(id) ON DELETE CASCADE,
    infos_pratiques  TEXT
);

CREATE TABLE sejour_participant (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id          BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    eleve_id           BIGINT REFERENCES eleve(id) ON DELETE SET NULL,
    utilisateur_id     BIGINT REFERENCES utilisateur(id) ON DELETE SET NULL,
    nom                VARCHAR(120) NOT NULL,
    prenom             VARCHAR(120) NOT NULL,
    plongeur           BOOLEAN NOT NULL DEFAULT TRUE,
    telephone          VARCHAR(30),
    email              VARCHAR(180),
    regimes            VARCHAR(200),
    regime_precision   VARCHAR(300),
    urgence_nom        VARCHAR(120),
    urgence_telephone  VARCHAR(30),
    arrivee_date       DATE,
    arrivee_heure      TIME,
    arrivee_transport  VARCHAR(20),
    arrivee_numero     VARCHAR(30),
    arrivee_lieu       VARCHAR(120),
    depart_date        DATE,
    depart_heure       TIME,
    depart_transport   VARCHAR(20),
    depart_numero      VARCHAR(30),
    depart_lieu        VARCHAR(120),
    remarques          TEXT
);
CREATE INDEX ix_sejour_participant_sortie ON sejour_participant(sortie_id);

CREATE TABLE sejour_voiture (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id      BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    nom            VARCHAR(120) NOT NULL,
    places         INTEGER NOT NULL,
    conducteur_id  BIGINT REFERENCES sejour_participant(id) ON DELETE SET NULL,
    trajet         VARCHAR(200),
    remarques      TEXT,
    CONSTRAINT ck_sejour_voiture_places CHECK (places BETWEEN 1 AND 9)
);

CREATE TABLE sejour_voiture_passager (
    voiture_id      BIGINT NOT NULL REFERENCES sejour_voiture(id) ON DELETE CASCADE,
    participant_id  BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    PRIMARY KEY (voiture_id, participant_id)
);

CREATE TABLE sejour_logement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id  BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    nom        VARCHAR(120) NOT NULL,
    adresse    VARCHAR(300),
    remarques  TEXT
);

CREATE TABLE sejour_chambre (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logement_id  BIGINT NOT NULL REFERENCES sejour_logement(id) ON DELETE CASCADE,
    nom          VARCHAR(120) NOT NULL,
    couchages    INTEGER NOT NULL,
    remarques    VARCHAR(300),
    ordre        INTEGER NOT NULL,
    CONSTRAINT ck_sejour_chambre_couchages CHECK (couchages BETWEEN 1 AND 30)
);

-- Une chambre par participant au plus.
CREATE TABLE sejour_chambre_occupant (
    chambre_id      BIGINT NOT NULL REFERENCES sejour_chambre(id) ON DELETE CASCADE,
    participant_id  BIGINT NOT NULL REFERENCES sejour_participant(id) ON DELETE CASCADE,
    PRIMARY KEY (chambre_id, participant_id),
    CONSTRAINT uq_sejour_chambre_occupant UNIQUE (participant_id)
);

-- categorie : DOCUMENTS, PLONGEE ou SEJOUR.
CREATE TABLE sejour_affaire (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id     BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    categorie     VARCHAR(20) NOT NULL,
    libelle       VARCHAR(200) NOT NULL,
    indispensable BOOLEAN NOT NULL DEFAULT FALSE,
    ordre         INTEGER NOT NULL
);

-- Programme : rendez-vous, repas, visites... Les plongées de la sortie
-- s'y ajoutent à l'affichage, lues sur ses séances.
CREATE TABLE sejour_evenement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id    BIGINT NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    jour         DATE NOT NULL,
    heure_debut  TIME,
    heure_fin    TIME,
    titre        VARCHAR(160) NOT NULL,
    lieu         VARCHAR(160),
    details      TEXT
);
CREATE INDEX ix_sejour_evenement_sortie ON sejour_evenement(sortie_id);
