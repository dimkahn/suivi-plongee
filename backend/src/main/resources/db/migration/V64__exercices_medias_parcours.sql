-- ============================================================
--  Base d'exercices : un vrai parcours de formation (choix du club, 2026).
--
--  1. Conseils de l'encadrant (exercice_competence.conseils) : points
--     de vigilance, erreurs fréquentes et remédiation, à côté du
--     déroulement et du critère de réussite.
--  2. Photos d'un exercice (photo_exercice) : plusieurs par exercice,
--     avec une légende. Table séparée, comme schema_exercice, pour ne
--     jamais alourdir les lectures de la base d'exercices. Le dépôt
--     exige que les personnes reconnaissables aient donné leur accord
--     (droit à l'image), règle du serveur.
--  3. Vidéos d'un exercice (video_exercice) : des liens (chaîne du
--     club, fichier publié sous /medias/), pas des fichiers en base.
--  4. Exercices d'une période de progression
--     (periode_progression_exercice) : la progression type ne dit plus
--     seulement quels blocs se travaillent de tel mois à tel mois, mais
--     quels exercices, de l'initiation à la maîtrise. Rangés dans
--     l'ordre des blocs puis des exercices, sans ordre propre.
-- ============================================================

ALTER TABLE exercice_competence ADD COLUMN conseils TEXT;

CREATE TABLE photo_exercice (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercice_id    BIGINT       NOT NULL REFERENCES exercice_competence(id) ON DELETE CASCADE,
    contenu        BYTEA        NOT NULL,
    type_contenu   VARCHAR(30)  NOT NULL,
    legende        VARCHAR(200),
    ordre          INT          NOT NULL DEFAULT 0,
    depose_le      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_photo_exercice_type CHECK (type_contenu IN ('image/jpeg', 'image/png'))
);

CREATE INDEX ix_photo_exercice_exercice ON photo_exercice(exercice_id);

CREATE TABLE video_exercice (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercice_id    BIGINT       NOT NULL REFERENCES exercice_competence(id) ON DELETE CASCADE,
    adresse        VARCHAR(500) NOT NULL,
    legende        VARCHAR(200),
    ordre          INT          NOT NULL DEFAULT 0
);

CREATE INDEX ix_video_exercice_exercice ON video_exercice(exercice_id);

CREATE TABLE periode_progression_exercice (
    periode_id     BIGINT NOT NULL REFERENCES periode_progression(id) ON DELETE CASCADE,
    exercice_id    BIGINT NOT NULL REFERENCES exercice_competence(id) ON DELETE CASCADE,
    PRIMARY KEY (periode_id, exercice_id)
);

CREATE INDEX ix_periode_progression_exercice_exercice ON periode_progression_exercice(exercice_id);
