-- La présentation des journées du programme d'un séjour, comme un carnet de
-- voyage (demande du club, 2026) : pour un jour, un titre (« Jour 1 — Cabo
-- Ledo »), le trajet, ce qu'on y verra, un conseil, l'hébergement, et
-- quelques photos des lieux. Les rendez-vous du jour restent dans
-- sejour_evenement. Une journée par jour du séjour ; tout part avec la sortie.

CREATE TABLE sejour_journee (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sortie_id    BIGINT       NOT NULL REFERENCES sortie(id) ON DELETE CASCADE,
    jour         DATE         NOT NULL,
    titre        VARCHAR(160),
    trajet       VARCHAR(300),
    descriptif   TEXT,
    conseil      TEXT,
    hebergement  VARCHAR(300),
    CONSTRAINT uq_sejour_journee UNIQUE (sortie_id, jour)
);

-- Photos des lieux (pas de personnes) : JPEG ou PNG, réduites par le téléphone.
CREATE TABLE sejour_journee_photo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journee_id    BIGINT       NOT NULL REFERENCES sejour_journee(id) ON DELETE CASCADE,
    contenu       BYTEA        NOT NULL,
    type_contenu  VARCHAR(30)  NOT NULL CHECK (type_contenu IN ('image/jpeg', 'image/png')),
    ajoutee_le    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_sejour_journee_photo ON sejour_journee_photo(journee_id);
