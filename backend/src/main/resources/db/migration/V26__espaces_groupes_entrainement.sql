CREATE TABLE groupe_entrainement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saison_id          BIGINT NOT NULL REFERENCES saison(id) ON DELETE CASCADE,
    nom                VARCHAR(80) NOT NULL,
    ordre              INTEGER NOT NULL,
    niveau_prepare     VARCHAR(2) CHECK (niveau_prepare IN ('N1', 'N2', 'N3')),
    espace_attitre_id  BIGINT REFERENCES espace_bassin(id) ON DELETE SET NULL
);

CREATE TABLE groupe_entrainement_encadrant (
    groupe_id       BIGINT NOT NULL REFERENCES groupe_entrainement(id) ON DELETE CASCADE,
    utilisateur_id  BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    PRIMARY KEY (groupe_id, utilisateur_id)
);

CREATE TABLE groupe_entrainement_eleve (
    groupe_id  BIGINT NOT NULL REFERENCES groupe_entrainement(id) ON DELETE CASCADE,
    eleve_id   BIGINT NOT NULL REFERENCES eleve(id) ON DELETE CASCADE,
    PRIMARY KEY (groupe_id, eleve_id)
);
