-- ============================================================
--  Planning du bassin, lot 1 : espaces et groupes d'entrainement.
--
--  espace_bassin : les lignes d'eau de la piscine et la fosse, la ou un
--  groupe peut etre place un soir d'entrainement. capacite et
--  profondeur_max sont indicatives (avertissements du planning, pas de
--  refus) ; NULL = sans objet ou inconnue.
--
--  groupe_entrainement : groupe de la saison (Debutants, Perfect N1,
--  Prepa N2...), avec ses encadrants attitres, sa ligne d'eau attitree et
--  ses eleves, ranges par l'admin. Sans rapport avec groupe_plongeurs
--  (V13), qui compose les palanquees d'un sejour. niveau_prepare (N1/N2/N3)
--  sert seulement a suggerer le groupe d'un eleve d'apres son cursus en
--  cours ; NULL pour un groupe sans formation (Perfect N1, N2+).
--
--  Un eleve est dans au plus un groupe par saison : regle tenue par
--  GroupeEntrainementService (la saison n'est pas une colonne de la table
--  de liaison).
-- ============================================================

CREATE TABLE espace_bassin (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom             VARCHAR(60) NOT NULL,
    type            VARCHAR(10) NOT NULL CHECK (type IN ('LIGNE', 'FOSSE')),
    ordre           INTEGER NOT NULL,
    profondeur_max  INTEGER,
    capacite        INTEGER,
    actif           BOOLEAN NOT NULL DEFAULT TRUE
);

